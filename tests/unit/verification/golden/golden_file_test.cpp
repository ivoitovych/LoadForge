GoldenVector sample() {
  GoldenVector vector;
  vector.key =
      GoldenKey{"compression", 3, simd::IsaPath::kAvx2, 0xFEEDFACECAFEBEEFULL, 1U << 20U, 0, 4, 2};
  vector.units = {UnitDigest{0x0123456789ABCDEFULL, 0x1ULL},
                  UnitDigest{0xFFFFFFFFFFFFFFFFULL, 0x0ULL}};
  vector.digest = 0x995DC9BBDF1939FAULL;
  return vector;
}

constexpr std::string_view kSampleBody =
    "loadforge-golden 1\n"
    "workload compression\n"
    "version 3\n"
    "isa avx2\n"
    "seed 0xfeedfacecafebeef\n"
    "footprint_bytes 1048576\n"
    "decomposition 0\n"
    "resolved_decomposition 4\n"
    "units 2\n"
    "unit 0 input 0x0123456789abcdef output 0x0000000000000001\n"
    "unit 1 input 0xffffffffffffffff output 0x0000000000000000\n"
    "digest 0x995dc9bbdf1939fa\n";

constexpr std::string_view kHeader =
    "# LoadForge golden vector: a regression tripwire, not an oracle (docs/verification.md "
    "§4).\n"
    "# Generated by the code it checks. Regenerate only deliberately, and say why.\n";

GoldenError refused(const std::string& text) {
  const auto parsed = parse_golden(text);
  EXPECT_FALSE(parsed.has_value()) << text;
  return parsed.has_value() ? GoldenError{} : parsed.error();
}

/// The sample with line `line` (1-based, of kSampleBody) replaced.
std::string with_line(std::size_t line, std::string_view replacement) {
  std::string text(kSampleBody);
  std::size_t start = 0;
  for (std::size_t skip = 1; skip < line; ++skip) {
    start = text.find('\n', start) + 1;
  }
  const std::size_t end = text.find('\n', start);
  text.replace(start, end - start, replacement);
  return text;
}

TEST(GoldenFile, IsTheDocumentedFormatByteForByte) {
  EXPECT_EQ(format_golden(sample()), std::string(kHeader) + std::string(kSampleBody));
}

TEST(GoldenFile, ANoteBecomesCommentLines) {
  EXPECT_EQ(format_golden(sample(), "Recorded on a test machine.\nBecause the codec changed."),
            std::string(kHeader) + "# Recorded on a test machine.\n# Because the codec changed.\n" +
                std::string(kSampleBody));
  EXPECT_EQ(format_golden(sample(), "one line\n"),
            std::string(kHeader) + "# one line\n" + std::string(kSampleBody))
      << "a trailing newline adds no empty comment";
}

TEST(GoldenFile, ReadsBackWhatItWrote) {
  const auto parsed = parse_golden(format_golden(sample(), "a note"));
  ASSERT_TRUE(parsed.has_value()) << describe(parsed.error());
  EXPECT_EQ(parsed.value(), sample());
  GoldenVector widest = sample();
  widest.key.version = std::numeric_limits<std::uint32_t>::max();
  widest.key.footprint_bytes = std::numeric_limits<std::uint64_t>::max();
  widest.key.decomposition = std::numeric_limits<std::uint32_t>::max();
  widest.key.resolved_decomposition = 1;
  widest.key.seed = 0;
  widest.key.isa = simd::IsaPath::kNeon;
  widest.key.workload = "a";
  const auto back = parse_golden(format_golden(widest));
  ASSERT_TRUE(back.has_value()) << describe(back.error());
  EXPECT_EQ(back.value(), widest);
}

TEST(GoldenFile, CommentsAndEmptyLinesAnywhereAndNoFinalNewline) {
  std::string text = "\n# leading\n" + std::string(kSampleBody);
  text.insert(text.find("version"), "# between\n\n");
  text.pop_back();
  const auto parsed = parse_golden(text);
  ASSERT_TRUE(parsed.has_value()) << describe(parsed.error());
  EXPECT_EQ(parsed.value(), sample());
}

TEST(GoldenFile, EachKeyLineIsRefusedWithItsLineNumber) {
  struct Case {
    std::size_t line;
    std::string_view text;
    std::string_view detail;
  };
  const std::vector<Case> cases = {
      {1, "loadforge-golden 2", "expected 'loadforge-golden 1', found 'loadforge-golden 2'"},
      {2, "workloads compression", "expected 'workload ...', found 'workloads compression'"},
      {2, "workload", "expected 'workload ...', found 'workload'"},
      {2, "work", "expected 'workload ...', found 'work'"},
      {2, "workload Compression", "workload 'Compression' is not a valid workload name"},
      {3, "version 0", "version 0: a workload's version is at least 1"},
      {3, "version 4294967296",
       "version '4294967296' is not a decimal from 0 to 4294967295 without sign or leading "
       "zeros"},
      {3, "version 03",
       "version '03' is not a decimal from 0 to 4294967295 without sign or leading zeros"},
      {3, "version +3",
       "version '+3' is not a decimal from 0 to 4294967295 without sign or leading zeros"},
      {3, "version 3a",
       "version '3a' is not a decimal from 0 to 4294967295 without sign or leading zeros"},
      {3, "version ",
       "version '' is not a decimal from 0 to 4294967295 without sign or leading zeros"},
      {4, "isa sse2", "isa 'sse2' is not an ISA path"},
      {5, "seed 0xFEEDFACECAFEBEEF",
       "seed '0xFEEDFACECAFEBEEF' is not 0x and sixteen lower-case hexadecimal digits"},
      {5, "seed 0xfeedfacecafebee",
       "seed '0xfeedfacecafebee' is not 0x and sixteen lower-case hexadecimal digits"},
      {5, "seed 0Xfeedfacecafebeef",
       "seed '0Xfeedfacecafebeef' is not 0x and sixteen lower-case hexadecimal digits"},
      {5, "seed 0xfeedfacecafebeeg",
       "seed '0xfeedfacecafebeeg' is not 0x and sixteen lower-case hexadecimal digits"},
      {5, "seed 0xfeedfacecafebee:",
       "seed '0xfeedfacecafebee:' is not 0x and sixteen lower-case hexadecimal digits"},
      {5, "seed 0xfeedfacecafebee/",
       "seed '0xfeedfacecafebee/' is not 0x and sixteen lower-case hexadecimal digits"},
      {6, "footprint_bytes 18446744073709551616",
       "footprint_bytes '18446744073709551616' is not a decimal from 0 to 18446744073709551615 "
       "without sign or leading zeros"},
      {7, "decomposition -1",
       "decomposition '-1' is not a decimal from 0 to 4294967295 without sign or leading "
       "zeros"},
      {8, "resolved_decomposition 0",
       "resolved_decomposition 0: a plan's decomposition is never 0"},
      {8, "resolved_decomposition x",
       "resolved_decomposition 'x' is not a decimal from 0 to 4294967295 without sign or "
       "leading zeros"},
      {9, "units 0", "units 0: a vector of no unit would compare nothing"},
      {9, "units two",
       "units 'two' is not a decimal from 0 to 18446744073709551615 without sign or leading "
       "zeros"},
      {10, "unit 1 input 0x0123456789abcdef output 0x0000000000000001",
       "expected 'unit 0 input ...', found 'unit 1 input 0x0123456789abcdef output "
       "0x0000000000000001'"},
      {10, "units 0 input 0x0123456789abcdef output 0x0000000000000001",
       "expected 'unit ...', found 'units 0 input 0x0123456789abcdef output "
       "0x0000000000000001'"},
      {10, "unit 0 input 0x0123 output 0x0000000000000001",
       "unit input digest '0x0123 output 0x00' is not 0x and sixteen lower-case hexadecimal "
       "digits"},
      {10, "unit 0 input 0x0123456789abcdef outputs 0x0000000000000001",
       "expected ' output ' after unit 0's input digest"},
      {10, "unit 0 input 0x0123456789abcdef output 0x00000000000000011",
       "unit output digest '0x00000000000000011' is not 0x and sixteen lower-case hexadecimal "
       "digits"},
      {12, "digest 0x995dc9bbdf1939f",
       "digest '0x995dc9bbdf1939f' is not 0x and sixteen lower-case hexadecimal digits"},
      {12, "digests 0x995dc9bbdf1939fa",
       "expected 'digest ...', found 'digests 0x995dc9bbdf1939fa'"},
  };
  for (const Case& entry : cases) {
    const GoldenError error = refused(with_line(entry.line, entry.text));
    EXPECT_EQ(error.line, entry.line) << entry.text;
    EXPECT_EQ(error.detail, entry.detail) << entry.text;
  }
}

TEST(GoldenFile, AFileThatEndsEarlyNamesWhatWasExpected) {
  const std::vector<std::pair<std::string_view, std::string_view>> cuts = {
      {"", "'loadforge-golden 1'"},
      {"loadforge-golden 1\n", "'workload'"},
      {"loadforge-golden 1\nworkload compression\n", "'version'"},
  };
  for (const auto& [text, wanted] : cuts) {
    const GoldenError error = refused(std::string(text));
    EXPECT_EQ(error.detail, "the file ends where " + std::string(wanted) + " was expected");
  }
  const std::string body(kSampleBody);
  for (const std::string_view key :
       {"isa", "seed", "footprint_bytes", "decomposition", "resolved_decomposition", "units",
        "unit 0", "unit 1", "digest"}) {
    const std::string cut = body.substr(0, body.find(std::string(key) + " "));
    const GoldenError error = refused(cut);
    EXPECT_NE(error.detail.find("the file ends where"), std::string::npos) << key;
  }
}

TEST(GoldenFile, NothingMayFollowTheDigest) {
  const GoldenError error = refused(std::string(kSampleBody) + "\n# fine\nunit 2 extra\n");
  EXPECT_EQ(error.line, 15U);
  EXPECT_EQ(error.detail, "'unit 2 extra' after the digest, which ends the vector");
}

TEST(GoldenFile, ErrorsDescribeThemselvesWithAndWithoutALine) {
  EXPECT_EQ(describe(GoldenError{7, "bad"}), "line 7: bad");
  EXPECT_EQ(describe(GoldenError{std::nullopt, "no unit"}), "no unit");
  contracts::expect_memberwise_equality(
      GoldenError{1, "a"},
      {[](GoldenError& e) { e.line = 2; }, [](GoldenError& e) { e.detail = "b"; }});
}

TEST(GoldenFile, EveryMemberOfTheValuesIsCompared) {
  using contracts::expect_memberwise_equality;
  expect_memberwise_equality(
      sample().key,
      {[](GoldenKey& k) { k.workload = "sort"; }, [](GoldenKey& k) { k.version = 9; },
       [](GoldenKey& k) { k.isa = simd::IsaPath::kScalar; }, [](GoldenKey& k) { k.seed = 9; },
       [](GoldenKey& k) { k.footprint_bytes = 9; }, [](GoldenKey& k) { k.decomposition = 9; },
       [](GoldenKey& k) { k.resolved_decomposition = 9; }, [](GoldenKey& k) { k.units = 9; }});
  expect_memberwise_equality(
      UnitDigest{1, 2}, {[](UnitDigest& u) { u.input = 9; }, [](UnitDigest& u) { u.output = 9; }});
  expect_memberwise_equality(sample(), {[](GoldenVector& v) { v.key.units = 9; },
                                        [](GoldenVector& v) { v.units.pop_back(); },
                                        [](GoldenVector& v) { v.digest = 9; }});
}

TEST(GoldenFile, TheKeyRecreatesTheConfiguration) {
  EXPECT_EQ(config_of(sample().key),
            (workloads::WorkloadConfig{0xFEEDFACECAFEBEEFULL, 1U << 20U, 0, simd::IsaPath::kAvx2}));
}

